#!/usr/bin/env python3
"""Procedurally synthesizes all original SFX + the music loop for the game.

Provenance: every sound is generated by this script (no samples, no third-party
audio) -> licensed together with the project. Re-run to regenerate:
    python3 tools/gen_audio.py
Output: assets/audio/sfx/*.wav, assets/audio/music/*.wav (22.05 kHz mono 16-bit).
"""
import os
import wave
import numpy as np

SR = 22050
ROOT = os.path.join(os.path.dirname(__file__), "..", "assets", "audio")
rng = np.random.default_rng(7)


def t(d):
    return np.arange(int(SR * d)) / SR


def env(n, a=0.005, r=0.1, total=None):
    x = np.ones(n)
    na = max(1, int(a * SR))
    nr = max(1, int(r * SR))
    x[:na] = np.linspace(0, 1, na)
    if nr < n:
        x[-nr:] *= np.linspace(1, 0, nr)
    return x


def expdecay(d, k):
    return np.exp(-k * t(d))


def sine(f, d, ph=0):
    return np.sin(2 * np.pi * f * t(d) + ph)


def noise(d):
    return rng.uniform(-1, 1, int(SR * d))


def lowpass(x, a):
    y = np.zeros_like(x)
    acc = 0.0
    for i, v in enumerate(x):
        acc += a * (v - acc)
        y[i] = acc
    return y


def write(path, x, gain=0.8):
    x = np.asarray(x, dtype=np.float64)
    m = np.max(np.abs(x)) or 1.0
    x = x / m * gain
    data = (x * 32767).astype("<i2").tobytes()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data)


def bell(f, d, k=6.0):
    x = sine(f, d) + 0.4 * sine(f * 2.01, d) + 0.15 * sine(f * 3.02, d)
    return x * expdecay(d, k) * env(len(x), 0.003, 0.05)


def sfx():
    out = {}
    d = 0.09
    out["step_floor"] = (lowpass(noise(d), 0.15) * expdecay(d, 55) + 0.5 * sine(110, d) * expdecay(d, 60)), 0.35
    out["step_paw"] = (lowpass(noise(0.05), 0.08) * expdecay(0.05, 80)), 0.2
    out["coin"] = np.concatenate([bell(1318, 0.09, 20), bell(1760, 0.35, 9)]), 0.6
    out["correct"] = np.concatenate([bell(784, 0.12, 14), bell(988, 0.12, 14), bell(1175, 0.45, 7)]), 0.55
    out["hint"] = bell(523, 0.35, 9) * 0.7 + bell(659, 0.35, 9) * 0.5, 0.4
    out["pop"] = sine(660, 0.06) * expdecay(0.06, 60) + 0.5 * sine(990, 0.06) * expdecay(0.06, 80), 0.4
    dd = 0.25
    f = 180 * np.exp(-6 * t(dd))
    out["ball_bounce"] = (np.sin(2 * np.pi * np.cumsum(f) / SR) * expdecay(dd, 18) + 0.3 * lowpass(noise(dd), 0.3) * expdecay(dd, 50)), 0.6
    # meow: formant-ish sweep
    dm = 0.55
    fm = 520 + 260 * np.sin(np.pi * t(dm) / dm) - 120 * t(dm)
    ph = 2 * np.pi * np.cumsum(fm) / SR
    meow = (np.sin(ph) + 0.5 * np.sin(2 * ph) + 0.25 * np.sin(3 * ph)) * env(len(ph), 0.05, 0.2)
    out["meow"] = meow, 0.45
    dp = 1.4
    purr = lowpass(noise(dp), 0.05) * (0.6 + 0.4 * np.sin(2 * np.pi * 24 * t(dp))) * env(int(SR * dp), 0.2, 0.4)
    out["purr"] = purr, 0.35
    db = 0.18
    fb = 420 - 600 * t(db)
    pb = 2 * np.pi * np.cumsum(fb) / SR
    bark1 = (np.sign(np.sin(pb)) * 0.4 + np.sin(pb) + 0.4 * lowpass(noise(db), 0.4)) * env(len(pb), 0.01, 0.08)
    out["bark"] = np.concatenate([bark1, np.zeros(int(SR * 0.08)), bark1 * 0.8]), 0.45
    ds = 0.8
    out["splash"] = lowpass(noise(ds), 0.35) * expdecay(ds, 5) * (0.6 + 0.4 * np.sin(2 * np.pi * 9 * t(ds))), 0.4
    dbr = 0.5
    out["brush"] = (lowpass(noise(dbr), 0.5) - lowpass(noise(dbr), 0.05)) * (0.5 + 0.5 * np.abs(np.sin(2 * np.pi * 4 * t(dbr)))), 0.3
    dc = 0.7
    fc = 300 + 80 * np.sin(2 * np.pi * 3 * t(dc))
    out["creak"] = np.sin(2 * np.pi * np.cumsum(fc) / SR) * lowpass(noise(dc), 0.6) * env(int(SR * dc), 0.1, 0.2), 0.25
    out["click"] = lowpass(noise(0.03), 0.6) * expdecay(0.03, 150), 0.4
    dr = 3.0
    out["rain_loop"] = lowpass(noise(dr), 0.25) * 0.6 + lowpass(noise(dr), 0.03) * 0.4, 0.25
    dw = 3.0
    out["wind_loop"] = lowpass(noise(dw), 0.02) * (0.6 + 0.4 * np.sin(2 * np.pi * 0.33 * t(dw))), 0.25
    out["page"] = lowpass(noise(0.25), 0.4) * env(int(SR * 0.25), 0.05, 0.15), 0.3
    out["chest"] = np.concatenate([lowpass(noise(0.12), 0.2) * expdecay(0.12, 20), bell(1046, 0.15, 12), bell(1318, 0.15, 12), bell(1568, 0.6, 5)]), 0.55
    out["sparkle"] = sum(bell(f, 0.5, 9) * (0.6 ** i) for i, f in enumerate([1568, 2093, 2637])), 0.35
    dt = 0.4
    out["tv_on"] = lowpass(noise(dt), 0.9) * expdecay(dt, 6) + 0.3 * sine(1000, dt) * expdecay(dt, 10), 0.25
    out["tick"] = lowpass(noise(0.02), 0.9) * expdecay(0.02, 300), 0.3
    out["whoosh"] = lowpass(noise(0.35), 0.1) * np.sin(np.pi * t(0.35) / 0.35), 0.35
    out["yay"] = np.concatenate([bell(659, 0.1, 10), bell(784, 0.1, 10), bell(1046, 0.5, 6)]), 0.45
    out["eat"] = np.concatenate([lowpass(noise(0.05), 0.3) * expdecay(0.05, 60), np.zeros(int(SR * 0.08))] * 3), 0.3
    out["lap"] = np.concatenate([sine(300, 0.05) * expdecay(0.05, 50) + 0.4 * lowpass(noise(0.05), 0.3), np.zeros(int(SR * 0.09))] * 3), 0.3
    out["yawn"] = np.sin(2 * np.pi * np.cumsum(280 - 120 * t(0.6)) / SR) * env(int(SR * 0.6), 0.15, 0.3) * 0.6, 0.3
    return out


def music():
    # Gentle pentatonic lullaby-ish loop: soft pad + music-box melody, 24 s.
    bpm = 80
    beat = 60 / bpm
    bars = 8
    total = bars * 4 * beat
    n = int(SR * total)
    x = np.zeros(n)
    chords = [(261.63, 329.63, 392.0), (220.0, 261.63, 329.63), (174.61, 220.0, 261.63), (196.0, 246.94, 293.66)]
    for b in range(bars):
        ch = chords[b % 4]
        start = int(b * 4 * beat * SR)
        d = 4 * beat
        seg = sum(sine(f, d) * 0.12 + sine(f * 2, d) * 0.03 for f in ch)
        seg *= env(len(seg), 0.6, 0.8)
        x[start:start + len(seg)] += seg[: n - start]
    scale = [523.25, 587.33, 659.25, 783.99, 880.0, 1046.5]
    pattern = [0, 2, 4, 2, 3, 2, 1, 0, 2, 4, 5, 4, 3, 1, 2, -1]
    step = beat / 2
    for i in range(int(total / step)):
        idx = pattern[i % len(pattern)]
        if idx < 0 or (i % 7 == 6):
            continue
        f = scale[idx]
        s = int(i * step * SR)
        note = bell(f, 1.2, 4.5) * 0.18
        e = min(n, s + len(note))
        x[s:e] += note[: e - s]
    return x


if __name__ == "__main__":
    for name, (sig, gain) in sfx().items():
        write(os.path.join(ROOT, "sfx", name + ".wav"), sig, gain)
    write(os.path.join(ROOT, "music", "cozy_room.wav"), music(), 0.5)
    print("ok")
